  // --- TransIP MySQL Database Bridge Helpers ---
  const TRANSIP_VISITOR_API = 'https://www.paulvangeenen.nl/api/visitor_database.php?key=visitor-secret-key-paul-2026';

  async function queryTransipSql(sql: string) {
    try {
      const res = await fetch(`${TRANSIP_VISITOR_API}&action=execute_sql`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ sql })
      });
      if (!res.ok) return null;
      const json = await res.json();
      return json?.success ? json.data : null;
    } catch (e) {
      console.error('[TransIP SQL Error]:', e);
      return null;
    }
  }

  async function fetchTransipAnalytics(action: string, options: { method?: string; body?: any; params?: Record<string, string> } = {}) {
    try {
      let url = `${TRANSIP_VISITOR_API}&action=${encodeURIComponent(action)}`;
      if (options.params) {
        for (const [k, v] of Object.entries(options.params)) {
          url += `&${encodeURIComponent(k)}=${encodeURIComponent(v)}`;
        }
      }
      const fetchOptions: RequestInit = {
        method: options.method || 'GET',
        headers: { 'Content-Type': 'application/json' },
      };
      if (options.body && options.method && ['POST', 'PUT', 'DELETE'].includes(options.method)) {
        fetchOptions.body = JSON.stringify(options.body);
      }
      const res = await fetch(url, fetchOptions);
      if (!res.ok) return null;
      return await res.json();
    } catch (e) {
      console.error(`[TransIP Analytics Error] action ${action}:`, e);
      return null;
    }
  }

  async function syncToTransipAnalytics(action: string, payload: any) {
    try {
      const bridgeUrl = `${TRANSIP_VISITOR_API}&action=${encodeURIComponent(action)}`;
      fetch(bridgeUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      }).catch(() => {});
    } catch {}
  }

