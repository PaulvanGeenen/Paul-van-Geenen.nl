export type MusicLanguage = 'nl' | 'en';

export const isCountryNetherlands = (country?: string): boolean => {
  if (!country) return true; // default safely
  const c = country.trim().toLowerCase();
  return c === 'nederland' || c === 'the netherlands' || c === 'netherlands' || c === 'nl';
};

export const getInitialMusicLanguage = (): MusicLanguage => {
  if (typeof window === 'undefined') return 'nl';

  // 1. Manual user override stored in localStorage
  const saved = localStorage.getItem('pv_music_lang');
  if (saved === 'nl' || saved === 'en') {
    return saved;
  }

  // 2. Check cached geolocation from sessionStorage (set during analytics)
  const cachedCountry = sessionStorage.getItem('pv_user_country');
  if (cachedCountry) {
    return isCountryNetherlands(cachedCountry) ? 'nl' : 'en';
  }

  // 3. Fallback to browser language
  const navLang = (navigator.language || (navigator.languages && navigator.languages[0]) || '').toLowerCase();
  if (navLang.startsWith('nl')) {
    return 'nl';
  }

  // Outside NL or foreign browser language -> default to English
  return 'en';
};

export const setStoredMusicLanguage = (lang: MusicLanguage) => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('pv_music_lang', lang);
    sessionStorage.setItem('pv_music_lang', lang);
  } catch (e) {}
};

